import type { SceneGraphDocument, SceneNode } from "../model/types";

const NOW = 1_726_444_800_000;

function scene(
  partial: Omit<SceneNode, "schemaVersion" | "createdAt" | "updatedAt" | "durationMs"> & {
    durationMs?: number;
  },
): SceneNode {
  const durationMs = partial.durationMs ?? partial.endMs - partial.startMs;
  return {
    ...partial,
    durationMs,
    schemaVersion: SCHEMA_VERSION,
    createdAt: NOW,
    updatedAt: NOW,
  };
}

